#!/usr/bin/env python3
"""Generate/check deterministic identity from explicit release inputs and Worker sources."""
import hashlib,json,sys,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
inputs=json.loads((root/'release-inputs.json').read_text())
def valid_version(value):return isinstance(value,str) and re.fullmatch(r"[0-9]{1,6}\.[0-9]{1,6}\.[0-9]{1,6}",value) is not None
if set(inputs)!={'backendRelease','toolSchemaVersion','supportedPackage'} or not valid_version(inputs['backendRelease']) or not valid_version(inputs['toolSchemaVersion']):raise SystemExit('Invalid reviewed release inputs.')
package=inputs['supportedPackage']
if not isinstance(package,dict) or set(package)!={'minimum','maximumExclusive'} or not all(valid_version(value) for value in package.values()) or tuple(map(int,package['minimum'].split('.')))>=tuple(map(int,package['maximumExclusive'].split('.'))):raise SystemExit('Invalid reviewed package range.')
paths=[root/'release-inputs.json',Path(__file__).resolve()]
for part in ['chatgpt-auth','chatgpt-mcp','companion-workspace']:
 paths+=list((root/part/'src').rglob('*.ts'))
 paths += [p for pattern in ['package*.json','wrangler*','tsconfig.json'] for p in (root/part).glob(pattern) if p.is_file()]
paths += [p for p in (root/'shared').glob('*.ts') if p.name!='build-identity.generated.ts']
digest=hashlib.sha256()
for path in sorted(set(paths)):
 digest.update(str(path.relative_to(root)).encode()+b'\0'+path.read_bytes()+b'\0')
value={**inputs,'buildHash':digest.hexdigest()}
target=root/'shared/build-identity.generated.ts'
content='// Generated by workers/scripts/generate-build-identity.py; do not edit.\nexport const buildIdentity = '+json.dumps(value,indent=2)+' as const;\n'
if '--check' in sys.argv:
 if not target.exists() or target.read_text()!=content:raise SystemExit('Stale Worker identity; regenerate from reviewed release inputs.')
else:target.write_text(content)
