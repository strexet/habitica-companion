#!/usr/bin/env python3
"""Mirror the reviewed diagnostic sanitizer allowlists for the Worker boundary."""
import json,re
from pathlib import Path
root=Path(__file__).resolve().parents[2]
s=(root/'src/Habitica.Domain/Diagnostics/DiagnosticsLogSanitizer.cs').read_text()
def strings(name):
    body=s.split(' '+name+' =',1)[1].split('};',1)[0]
    return re.findall(r'"([^"\\]*)"',body)
catalog={name[0].lower()+name[1:]:strings(name) for name in ['Operations','Counts','Measurements','Flags','Sections','Statuses','SectionLists']}
choices=s.split(' Choices =',1)[1].split('};',1)[0]
catalog['choices']={key:re.findall(r'"([^"\\]*)"',values) for key,values in re.findall(r'\["([^"]+)"\] = \[([^\]]+)\]',choices)}
catalog['operations'].append('app-operation')
out='// Generated by workers/scripts/generate-diagnostic-catalog.py from DiagnosticsLogSanitizer.\nexport const diagnosticCatalog = '+json.dumps(catalog,indent=2)+' as const;\n'
(root/'workers/shared/diagnostic-catalog.ts').write_text(out)
